#include<iostream>
#include<cstdio>
using namespace std;
double A[6];
double ma[6][6][6][6][6][6][6];
int main(){
    int i[6],j,n,k;
    double p;
    for(j=0;j<6;j++){
        cin>>A[j];
    }
    for(i[0]=0;i[0]<6;i[0]++){
        for(i[1]=0;i[1]<6;i[1]++){
            for(i[2]=0;i[2]<6;i[2]++){
                for(i[3]=0;i[3]<6;i[3]++){
                    for(i[4]=0;i[4]<6;i[4]++){
                        for(i[5]=0;i[5]<6;i[5]++){
                            for(j=0;j<6;j++){
                                ma[i[0]][i[1]][i[2]][i[3]][i[4]][i[5]][0]=max(ma[i[0]][i[1]][i[2]][i[3]][i[4]][i[5]][0],i[j]*A[j]);
                            }
                        }
                    }
                }
            }
        }
    }
    for(k=1;k<=3;k++){
        for(n=1;n<=5;n++){
            for(i[0]=0;i[0]<6;i[0]++){
                for(i[1]=0;i[1]<6;i[1]++){
                    for(i[2]=0;i[2]<6;i[2]++){
                        for(i[3]=0;i[3]<6;i[3]++){
                            for(i[4]=0;i[4]<6;i[4]++){
                                for(i[5]=0;i[5]<6;i[5]++){
                                    p=0;
                                    if(i[0]<5)p=p+max(ma[i[0]+1][i[1]][i[2]][i[3]][i[4]][i[5]][n-1],
                                        ma[i[0]][i[1]][i[2]][i[3]][i[4]][i[5]][n]);
                                    if(i[1]<5)p=p+ma[i[0]][i[1]+1][i[2]][i[3]][i[4]][i[5]][n-1];
                                    if(i[2]<5)p=p+ma[i[0]][i[1]][i[2]+1][i[3]][i[4]][i[5]][n-1];
                                    if(i[3]<5)p=p+ma[i[0]][i[1]][i[2]][i[3]+1][i[4]][i[5]][n-1];
                                    if(i[4]<5)p=p+ma[i[0]][i[1]][i[2]][i[3]][i[4]+1][i[5]][n-1];
                                    if(i[5]<5)p=p+ma[i[0]][i[1]][i[2]][i[3]][i[4]][i[5]+1][n-1];
                                    p=p/6;
                                    ma[i[0]][i[1]][i[2]][i[3]][i[4]][i[5]][n]=p;
                                }
                            }
                        }
                    }
                }
            }
        }
    }
    printf("%.10lf",ma[0][0][0][0][0][0][5]);
    return 0;
}